#!/usr/bin/env python3
"""Reopen and audit the final revised PDF, including its generated lists."""
from __future__ import annotations

import hashlib
import json
import re
import warnings
from pathlib import Path

import fitz

from build_revised_thesis import ROOT, scan_content

PDF = ROOT / "deliverables" / "These_revisee_BERKANE_Dhiyaddine.pdf"
BUILD_REPORT = ROOT / "audits" / "build_report.json"
OUT = ROOT / "audits" / "final_pdf_qa.json"


def flat(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


warnings.filterwarnings("ignore", category=FutureWarning)
build = json.loads(BUILD_REPORT.read_text(encoding="utf-8"))
doc = fitz.open(PDF)
page_texts = [page.get_text() for page in doc]
flat_pages = [flat(text) for text in page_texts]
all_text = "\n".join(page_texts)
scan = scan_content()

checks: dict[str, object] = {}
checks["page_count_matches_builder"] = len(doc) == build["pages"] and len(doc) > 0
checks["a4_pages"] = all(abs(page.rect.width - 595.276) < 1 and abs(page.rect.height - 841.89) < 1 for page in doc)
checks["not_encrypted"] = not doc.needs_pass

low_content = []
for index, page in enumerate(doc, 1):
    if len(page_texts[index - 1].strip()) < 20 and not page.get_images(full=True) and not page.get_drawings():
        low_content.append(index)
checks["no_blank_pages"] = not low_content

# Text outside the physical page is a strong clipping indicator. Running headers
# and footers are intentionally inside the page and therefore included safely.
outside = []
for index, page in enumerate(doc, 1):
    rect = page.rect
    for block in page.get_text("dict")["blocks"]:
        for line in block.get("lines", []):
            for span in line.get("spans", []):
                x0, y0, x1, y1 = span["bbox"]
                if x0 < -1 or y0 < -1 or x1 > rect.width + 1 or y1 > rect.height + 1:
                    outside.append({"page": index, "text": span["text"][:80], "bbox": span["bbox"]})
checks["no_text_outside_page"] = not outside

# Body text must start below the 15 mm running-header rule. The 40–54 pt
# band caught automatic-page-break overlaps that a full-page thumbnail missed.
header_band = []
for index, page in enumerate(doc, 1):
    for block in page.get_text("dict")["blocks"]:
        for line in block.get("lines", []):
            for span in line.get("spans", []):
                y0 = span["bbox"][1]
                if 40 < y0 < 54 and span["text"].strip():
                    header_band.append({"page": index, "y": y0, "text": span["text"][:100]})
checks["no_body_text_in_running_header_band"] = not header_band

# The footer must carry the physical PDF page number on every page after cover.
footer_mismatches = []
for index, page in enumerate(doc, 1):
    if index == 1:
        continue
    footer_text = " ".join(
        block[4] for block in page.get_text("blocks")
        if block[1] > 785 and block[3] < 830
    )
    if str(index) not in footer_text.split():
        footer_mismatches.append({"page": index, "footer": footer_text})
checks["page_footers_match_physical_pages"] = not footer_mismatches

# Check every generated outline destination against the heading on its page.
toc = doc.get_toc()
outline_mismatches = []
for level, title, page_number in toc:
    if level > 2 or not (1 <= page_number <= len(doc)):
        outline_mismatches.append({"title": title, "page": page_number, "reason": "bad destination"})
    elif flat(title) not in flat_pages[page_number - 1]:
        outline_mismatches.append({"title": title, "page": page_number, "reason": "heading absent on destination"})
checks["outline_destinations_match_headings"] = not outline_mismatches and len(toc) == build["outline_entries"]

# Lists of figures/tables are in the front matter. Compare complete caption text
# and the page number generated by the stable two-pass build.
front = flat("\n".join(page_texts[:12]))
caption_list_mismatches = []
for item in scan.captions:
    actual_page = build["caption_pages"].get(item.label)
    expected = flat(f"{item.label} — {item.title} {actual_page}")
    if expected not in front:
        caption_list_mismatches.append({"label": item.label, "expected": expected})
checks["caption_lists_match_titles_and_actual_pages"] = not caption_list_mismatches

forbidden = ["[[", "]]", "浸水", "214 références", "Error!", "PENDING", "�"]
forbidden_found = {token: all_text.count(token) for token in forbidden if token in all_text}
checks["no_unresolved_markers_or_known_source_defects"] = not forbidden_found

arabic = page_texts[3]
arabic_letters = len(re.findall(r"[\u0600-\u06ff]", arabic))
checks["arabic_abstract_has_real_glyph_text"] = arabic_letters > 1000 and "تتناول" in arabic and "الكلمات" in arabic
image_placements = sum(len(page.get_images(full=True)) for page in doc)
checks["expected_image_placements"] = image_placements == 23  # 2 logos + 21 figures

# Refresh the page-keyed inventory from the exact file that has just passed the
# checks above. Raw extraction order is retained; sorting Arabic by coordinates
# would scramble its logical reading order.
inventory = []
for index, page in enumerate(doc, 1):
    text = flat(page_texts[index - 1])
    inventory.append({
        "page": index,
        "chars": len(text),
        "words": len(text.split()),
        "images": len(page.get_images(full=True)),
        "drawings": len(page.get_drawings()),
        "start": text[:120],
    })
(ROOT / "audits" / "pdf_page_inventory.json").write_text(
    json.dumps(inventory, ensure_ascii=False, indent=2), encoding="utf-8"
)
checks["page_inventory_complete"] = len(inventory) == len(doc) and [row["page"] for row in inventory] == list(range(1, len(doc) + 1))

boolean_checks = {key: value for key, value in checks.items() if isinstance(value, bool)}
report = {
    "file": str(PDF), "bytes": PDF.stat().st_size, "sha256": sha256(PDF),
    "pages": len(doc), "outline_entries": len(toc), "image_placements": image_placements,
    "page_inventory_entries": len(inventory),
    "arabic_letters_extracted": arabic_letters,
    "checks": checks,
    "details": {
        "blank_pages": low_content, "outside_text": outside, "header_band_text": header_band,
        "footer_mismatches": footer_mismatches, "outline_mismatches": outline_mismatches,
        "caption_list_mismatches": caption_list_mismatches, "forbidden_found": forbidden_found,
    },
    "manual_visual_review": f"Contact sheets of all {len(doc)} pages, the full-size Arabic abstract, all 21 source figures and corrected full-size pages inspected separately.",
    "status": "pass" if all(boolean_checks.values()) else "fail",
}
OUT.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
print(json.dumps({key: value for key, value in report.items() if key != "details"}, ensure_ascii=False, indent=2))
if report["status"] != "pass":
    print(json.dumps(report["details"], ensure_ascii=False, indent=2))
raise SystemExit(0 if report["status"] == "pass" else 2)
